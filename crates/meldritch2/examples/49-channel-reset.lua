local graph = meldritch.graph()
local output = graph:module("output", "output")
local mix = graph:module("mix", "mix")
local left_level = graph:module("left_level", "gain", { gain = 0.25 })
local left_env = graph:module("left_env", "envelope", { attack = 1.0, release = 1.0 })
local left_osc = graph:module("left_osc", "sine", { frequency = 0.0 })
local left_pitch = graph:module("left_pitch", "constant", { value = 440.0 })
local left_gate = graph:module("left_gate", "constant", { value = 0.0 })
local right_level = graph:module("right_level", "gain", { gain = 0.25 })
local right_env = graph:module("right_env", "envelope", { attack = 1.0, release = 1.0 })
local right_osc = graph:module("right_osc", "sine", { frequency = 0.0 })
local right_pitch = graph:module("right_pitch", "constant", { value = 440.0 })
local right_gate = graph:module("right_gate", "constant", { value = 0.0 })
graph:connect(mix.out, output.input)
graph:connect(left_level.out, mix.left)
graph:connect(left_env.out, left_level.mod)
graph:connect(left_osc.out, left_level.input)
graph:connect(left_pitch.out, left_osc.fm_hz)
graph:connect(left_gate.out, left_env.gate)
graph:connect(right_level.out, mix.right)
graph:connect(right_env.out, right_level.mod)
graph:connect(right_osc.out, right_level.input)
graph:connect(right_pitch.out, right_osc.fm_hz)
graph:connect(right_gate.out, right_env.gate)
graph:control("left-pitch", left_pitch, "value", { min = 8.0, max = 13000.0 })
graph:control("left-gate", left_gate, "value", { min = 0.0, max = 1.0 })
graph:control("right-pitch", right_pitch, "value", { min = 8.0, max = 13000.0 })
graph:control("right-gate", right_gate, "value", { min = 0.0, max = 1.0 })
graph:midi_notes(1, "left-pitch", "left-gate")
graph:midi_notes(2, "right-pitch", "right-gate")
return graph
