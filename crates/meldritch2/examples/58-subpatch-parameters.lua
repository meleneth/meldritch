local amplifier = meldritch.subpatch("amplifier")
local gain = amplifier:module("gain", "gain", { gain = 0.5 })
amplifier:input("signal", gain.input)
amplifier:output("audio", gain.out)
amplifier:parameter("level", gain, "gain")

local wrapper = meldritch.subpatch("wrapper")
local inner = wrapper:instance("inner", amplifier)
wrapper:input("signal", inner.signal)
wrapper:output("audio", inner.audio)
wrapper:parameter("level", inner, "level")

local graph = meldritch.graph()
local source = graph:module("source", "constant", { value = 0.25 })
local left = graph:instance("left", wrapper)
local right = graph:instance("right", wrapper)
local mix = graph:module("mix", "mix")
local output = graph:module("output", "output")
graph:connect(source.out, left.signal)
graph:connect(source.out, right.signal)
graph:connect(left.audio, mix.left)
graph:connect(right.audio, mix.right)
graph:connect(mix.out, output.input)
graph:control("left-level", left, "level", { min = 0.0, max = 1.0 })
graph:control("right-level", right, "level", { min = 0.0, max = 1.0 })
graph:midi_cc("right-level", 1, 7)
return graph
